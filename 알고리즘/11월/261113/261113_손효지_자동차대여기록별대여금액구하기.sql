WITH RENTAL_DURATION AS (
    SELECT
        HISTORY_ID,
        CAR_ID,
        CAR_TYPE,
        DAILY_FEE,
        DATEDIFF(END_DATE, START_DATE) + 1 AS DURATION
    FROM CAR_RENTAL_COMPANY_RENTAL_HISTORY
    JOIN CAR_RENTAL_COMPANY_CAR USING (CAR_ID)
    WHERE CAR_TYPE = '트럭'
),
ADD_DISCOUNT_RATE AS (
    SELECT
        HISTORY_ID,
        DURATION,
        DAILY_FEE,
        COALESCE(DISCOUNT_RATE, 0) AS DISCOUNT_RATE
    FROM RENTAL_DURATION
    LEFT JOIN CAR_RENTAL_COMPANY_DISCOUNT_PLAN
        ON RENTAL_DURATION.CAR_TYPE
           = CAR_RENTAL_COMPANY_DISCOUNT_PLAN.CAR_TYPE
        AND DURATION_TYPE = CASE
            WHEN DURATION >= 90 THEN '90일 이상'
            WHEN DURATION >= 30 THEN '30일 이상'
            WHEN DURATION >= 7 THEN '7일 이상'
        END
)
SELECT
    HISTORY_ID,
    FLOOR(
        DURATION * DAILY_FEE * (1 - DISCOUNT_RATE / 100)
    ) AS FEE
FROM ADD_DISCOUNT_RATE
ORDER BY FEE DESC, HISTORY_ID DESC;