WITH MAY_SALES AS
(SELECT PRODUCT_ID, SUM(AMOUNT) AS TOTAL_AMOUNT
FROM FOOD_ORDER
WHERE DATE(PRODUCE_DATE) BETWEEN '2022-05-01' AND '2022-05-31'
GROUP BY PRODUCT_ID)
SELECT PRODUCT_ID, PRODUCT_NAME, (PRICE * TOTAL_AMOUNT) AS TOTAL_SALES
FROM FOOD_PRODUCT
JOIN MAY_SALES USING(PRODUCT_ID)
ORDER BY TOTAL_SALES DESC, PRODUCT_ID ASC;