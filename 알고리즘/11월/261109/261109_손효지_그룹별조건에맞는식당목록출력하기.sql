WITH RC AS (
    SELECT P.MEMBER_ID, COUNT(*) AS REVIEW_COUNT
    FROM MEMBER_PROFILE P
    JOIN REST_REVIEW R ON R.MEMBER_ID = P.MEMBER_ID
    GROUP BY P.MEMBER_ID
),
RANKED AS (
    SELECT MEMBER_ID,
           DENSE_RANK() OVER (ORDER BY REVIEW_COUNT DESC) AS REVIEW_RANK
    FROM RC
)
SELECT P.MEMBER_NAME,
       R.REVIEW_TEXT,
       DATE_FORMAT(R.REVIEW_DATE, '%Y-%m-%d') AS REVIEW_DATE
FROM RANKED K
JOIN MEMBER_PROFILE P ON P.MEMBER_ID = K.MEMBER_ID
JOIN REST_REVIEW R ON R.MEMBER_ID = K.MEMBER_ID
WHERE K.REVIEW_RANK = 1
ORDER BY REVIEW_DATE ASC, R.REVIEW_TEXT ASC;