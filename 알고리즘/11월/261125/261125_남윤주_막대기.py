'''
64cm 막대로 시작
자르고 붙여서 Xcm 만들기

가진 막대 길이 총합 X보다 크면 
가장 짧은 거 절반 자르고
하나버리고 남은 막대 길이 합이 X보다 크거나같으면
위에서 자른 막대의 절반 중 하나 버
'''
'''
64 32 16

64 32 16 8 4

64 32 16 8 4 2

X가 64보다 크면 64 빼고 그외에는 2로 나누고 빼고 반복
뺄 때마다 ans 1추가
X가 0이 될 때까지

'''

X = int(input())
ans = 0
num = 64
while X:
    if X >= num:
        X -= num
        ans += 1
    else:
        num /= 2

print(ans)